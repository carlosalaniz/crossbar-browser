// Harbor's build: takes no Dockerfile target, so each service gets deploy/Dockerfile plus a final
// stage that selects its target. Run after changing deploy/Dockerfile; a test checks they're in sync.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
export const HARBOR_TARGETS = { app: "app", browser: "browser-firewalled", proxy: "proxy" };

export function render(target) {
  const base = readFileSync(resolve(root, "deploy/Dockerfile"), "utf8");
  return `# GENERATED by scripts/harbor-dockerfiles.mjs from deploy/Dockerfile. Don't edit.\n${base}\nFROM ${target}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  for (const [svc, target] of Object.entries(HARBOR_TARGETS)) writeFileSync(resolve(root, `harbor/build/${svc}.Dockerfile`), render(target));
  console.log("wrote harbor/build/*.Dockerfile");
}
