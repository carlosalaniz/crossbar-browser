// Generates the scenario table in testsite/README.md from scenarios.json (between the markers).
// `node testsite/src/readme.ts` rewrites it; testsite/test/site.test.ts fails if it's stale.
import { readFileSync, writeFileSync } from "node:fs";
import { SCENARIOS } from "./scenarios.ts";

export const README = new URL("../README.md", import.meta.url);
const START = "<!-- scenarios:start (generated by node testsite/src/readme.ts; do not edit) -->";
const END = "<!-- scenarios:end -->";

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function scenarioTable(): string {
  const rows: string[] = [];
  let area = "";
  for (const s of SCENARIOS) {
    if (s.area !== area) {
      area = s.area;
      rows.push(`\n### ${area}\n`, "| Scenario | Path | Expected | Also |", "|---|---|---|---|");
    }
    const also = (s.checks ?? []).map((c) => `${cell(c.on)}: \`${c.outcome}\``).join("; ");
    rows.push(`| ${cell(s.title)}${s.mode === "live" ? " *(live-only)*" : ""} | \`${cell(s.host + s.path)}\` | \`${s.outcome}\` | ${also} |`);
  }
  return rows.join("\n").trim();
}

export function renderReadme(text: string): string {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error("README markers missing");
  return `${text.slice(0, a + START.length)}\n\n${scenarioTable()}\n\n${text.slice(b)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(README, renderReadme(readFileSync(README, "utf8")));
  console.log("README scenario table updated");
}
